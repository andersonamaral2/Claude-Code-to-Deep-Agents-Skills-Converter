def get_digital_content():
    """Retorna todo o conteúdo da Scoras Digital"""
    return SCORAS_DIGITAL_CONTENT

def get_service_by_keyword(keyword):
    """Busca serviço por palavra-chave"""
    keyword_lower = keyword.lower()
    service_id = SERVICE_KEYWORDS.get(keyword_lower)
    if service_id and service_id in SCORAS_DIGITAL_CONTENT:
        return SCORAS_DIGITAL_CONTENT[service_id]
    return None

def search_digital_content(query):
    """Busca conteúdo baseado na query"""
    query_lower = query.lower()
    results = []
    
    # Busca por palavras-chave
    for keyword in SERVICE_KEYWORDS:
        if keyword in query_lower:
            service_id = SERVICE_KEYWORDS[keyword]
            if service_id in SCORAS_DIGITAL_CONTENT:
                content = SCORAS_DIGITAL_CONTENT[service_id]
                results.append({
                    'id': service_id,
                    'titulo': content['titulo'],
                    'categoria': content['categoria'],
                    'descricao': content['descricao'],
                    'relevancia': 1.0
                })
    
    # Remove duplicatas
    seen_ids = set()
    unique_results = []
    for result in results:
        if result['id'] not in seen_ids:
            unique_results.append(result)
            seen_ids.add(result['id'])
    
    return unique_results 